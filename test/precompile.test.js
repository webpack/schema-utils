import fs from "fs";
import os from "os";
import path from "path";
import { pathToFileURL } from "url";

import { precompile, validate } from "../src";
import cli from "../src/cli";

import { getCheck } from "./helpers/precompiled";

const runtime = require("../src/runtime");

/**
 * `fs.rmSync` needs Node.js 14.14.0
 * @param {string} target file or directory to remove
 */
function remove(target) {
  if (fs.lstatSync(target).isDirectory()) {
    for (const name of fs.readdirSync(target)) {
      remove(path.join(target, name));
    }

    fs.rmdirSync(target);
  } else {
    fs.unlinkSync(target);
  }
}

describe("precompile", () => {
  /** @type {string} */
  let dir;

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "schema-utils-"));
  });

  afterEach(() => {
    remove(dir);
  });

  /**
   * @param {string} name file name
   * @param {object} content JSON content
   * @returns {string} path of the file
   */
  function writeJson(name, content) {
    const file = path.join(dir, name);

    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(content));

    return file;
  }

  /**
   * @param {string[]} args arguments
   * @returns {Promise<{ exitCode: number, log: string[], error: string[] }>} result
   */
  async function runCli(args) {
    /** @type {string[]} */
    const log = [];
    /** @type {string[]} */
    const error = [];
    const exitCode = await cli(args, {
      log: (message) => log.push(message),
      error: (message) => error.push(message),
    });

    return { exitCode, log, error };
  }

  describe("validate with a check", () => {
    const schema = {
      type: "object",
      properties: { name: { type: "string" } },
      additionalProperties: false,
    };

    it("should not run the full validation when the check passes", () => {
      const check = jest.fn(() => true);

      // The value is invalid, a passing check is trusted
      expect(() =>
        validate(schema, { name: 1 }, { name: "Plugin" }, check),
      ).not.toThrow();
      expect(check).toHaveBeenCalledTimes(1);
    });

    it("should run the full validation when the check fails", () => {
      expect(() =>
        validate(schema, { name: 1 }, { name: "Plugin" }, () => false),
      ).toThrow(/^Invalid configuration object\. Plugin has been initialized/);
    });

    it("should not throw when only the check fails", () => {
      expect(() =>
        validate(schema, { name: "a" }, { name: "Plugin" }, () => false),
      ).not.toThrow();
    });

    it("should check every item of an array", () => {
      const check = jest.fn(
        (value) =>
          typeof (/** @type {{ name: unknown }} */ (value).name) === "string",
      );

      expect(() =>
        validate(schema, [{ name: "a" }, { name: 1 }], {}, check),
      ).toThrow(/configuration\[1\]\.name should be a string/);
      expect(check).toHaveBeenCalledTimes(2);
    });

    it("should validate with a precompiled check", async () => {
      const check = await getCheck(schema);

      expect(() => validate(schema, { name: "a" }, {}, check)).not.toThrow();
      expect(() => validate(schema, { name: 1 }, {}, check)).toThrow(
        /configuration\.name should be a string/,
      );
    });
  });

  it("should generate a module with the banner", async () => {
    const code = await precompile({ type: "string" });

    expect(code).toMatch(
      /^\/\* eslint-disable \*\/\n\/\/ @ts-nocheck\n\/\*\n \* This file was automatically generated by "schema-utils"\./,
    );
  });

  it("should not keep annotations in the generated code", async () => {
    const code = await precompile({
      title: "Plugin options",
      description: "The options",
      type: "object",
      properties: {
        // A property named like an annotation is kept
        description: {
          description: "The description of the thing",
          link: "https://example.com/description",
          enum: ["a", "b"],
        },
      },
      definitions: {
        Unused: { description: "Never referenced", type: "string" },
      },
    });

    expect(code).not.toMatch(/Plugin options|The options|example\.com/);
    expect(code).toMatch(/"description"/);
  });

  it("should load the runtime helpers from schema-utils", async () => {
    const code = await precompile({
      type: "object",
      properties: {
        name: { type: "string", minLength: 2 },
        date: { type: "string", format: "date" },
        mode: { enum: [{ a: 1 }] },
      },
    });

    expect(code).not.toMatch(/require\("ajv/);
    expect(code).toMatch(
      /require\("schema-utils\/dist\/runtime"\)\.ucs2length/,
    );
    expect(code).toMatch(/require\("schema-utils\/dist\/runtime"\)\.formats/);
    expect(code).toMatch(/require\("schema-utils\/dist\/runtime"\)\.equal/);
  });

  it("should expose every runtime helper", () => {
    expect(runtime.equal({ a: [1] }, { a: [1] })).toBe(true);
    expect(runtime.ucs2length("😀")).toBe(1);
    expect(typeof runtime.uri.parse).toBe("function");
    expect(typeof runtime.formats.date).toBe("object");
  });

  it("should check instanceof", async () => {
    const check = await getCheck({
      type: "object",
      properties: {
        fn: { instanceof: "Function" },
        test: { instanceof: ["RegExp", "Function"] },
      },
    });

    expect(check({ fn: () => {}, test: /a/ })).toBe(true);
    expect(check({ fn: () => {}, test: () => {} })).toBe(true);
    expect(check({ fn: "a" })).toBe(false);
    expect(check({ test: "a" })).toBe(false);
  });

  it("should reject an unknown instanceof constructor", async () => {
    await expect(precompile({ instanceof: "Map" })).rejects.toThrow(
      'invalid "instanceof" keyword value Map',
    );
  });

  it("should check absolutePath", async () => {
    const check = await getCheck({
      type: "object",
      properties: {
        absolute: { type: "string", absolutePath: true },
        relative: { type: "string", absolutePath: false },
      },
    });

    expect(check({ absolute: "/a", relative: "a" })).toBe(true);
    expect(check({ absolute: "C:\\a" })).toBe(true);
    expect(check({ absolute: "file:///a" })).toBe(true);
    expect(check({ absolute: "a" })).toBe(false);
    expect(check({ absolute: "/a!b" })).toBe(false);
    expect(check({ relative: "/a" })).toBe(false);
  });

  it("should resolve an external $ref to a file", async () => {
    writeJson("definitions.json", {
      definitions: {
        Name: { description: "A name", type: "string" },
      },
    });

    const file = writeJson("options.json", {
      type: "object",
      properties: { name: { $ref: "./definitions.json#/definitions/Name" } },
    });
    const schema = JSON.parse(fs.readFileSync(file, "utf8"));

    schema.$id = pathToFileURL(file).href;

    const code = await precompile(schema);

    // Every path is relative to the schema, so the code is the same on every machine
    expect(code).not.toMatch(/file:/);
    expect(code).not.toContain(dir);
    expect(code).not.toMatch(/A name/);
  });

  it("should keep a file URL that is a value", async () => {
    const file = writeJson("options.json", {});
    const url = pathToFileURL(path.join(dir, "assets/logo.png")).href;
    const check = await getCheck({
      $id: pathToFileURL(file).href,
      enum: [url],
    });

    expect(check(url)).toBe(true);
    expect(check("assets/logo.png")).toBe(false);
  });

  it("should not set undefinedAsNull on a value without a parent", async () => {
    const check = await getCheck({ undefinedAsNull: true, enum: [null] });

    expect(check(undefined)).toBe(false);
    expect(check(null)).toBe(true);
    expect(
      check(undefined, { parentData: [undefined], parentDataProperty: 0 }),
    ).toBe(true);
  });

  it("should load an external $ref with loadSchema", async () => {
    const loadSchema = jest.fn(async () => ({ type: "string" }));

    await precompile(
      {
        $id: "https://example.com/options.json",
        $ref: "https://example.com/name.json",
      },
      { loadSchema },
    );

    expect(loadSchema).toHaveBeenCalledWith("https://example.com/name.json");
  });

  it("should not load an external $ref that is not a file", async () => {
    await expect(
      precompile({
        $id: "https://example.com/options.json",
        $ref: "https://example.com/name.json",
      }),
    ).rejects.toThrow(
      'Cannot load the schema "https://example.com/name.json", pass a `loadSchema` option to load it',
    );
  });

  describe("cli", () => {
    it("should print the usage", async () => {
      const result = await runCli(["--help"]);

      expect(result.exitCode).toBe(0);
      expect(result.log[0]).toMatch(/^Usage: schema-utils precompile/);
    });

    it("should fail without a command", async () => {
      const result = await runCli([]);

      expect(result.exitCode).toBe(1);
      expect(result.error[0]).toMatch(/^Usage: schema-utils precompile/);
    });

    it("should fail with an unknown command", async () => {
      const result = await runCli(["compile"]);

      expect(result.exitCode).toBe(1);
      expect(result.error[0]).toMatch(/^Unknown command "compile"/);
    });

    it("should fail with an unknown option", async () => {
      const result = await runCli(["precompile", "--write", "options.json"]);

      expect(result.exitCode).toBe(1);
      expect(result.error[0]).toMatch(/^Unknown option "--write"/);
    });

    it("should fail without a schema", async () => {
      const result = await runCli(["precompile", "--check"]);

      expect(result.exitCode).toBe(1);
      expect(result.error[0]).toMatch(/^No schema given/);
    });

    it("should write the check next to the schema and keep it up to date", async () => {
      writeJson("definitions.json", {
        definitions: { Name: { type: "string" } },
      });

      const file = writeJson("src/options.json", {
        type: "object",
        properties: {
          name: { $ref: "../definitions.json#/definitions/Name" },
        },
      });
      const checkFile = path.join(dir, "src/options.check.js");

      let result = await runCli(["precompile", "--check", file]);

      expect(result.exitCode).toBe(1);
      expect(result.error[0]).toMatch(/options\.check\.js" is missing/);
      expect(fs.existsSync(checkFile)).toBe(false);

      result = await runCli(["precompile", file]);

      expect(result.exitCode).toBe(0);
      expect(result.log[0]).toMatch(/options\.check\.js" updated/);

      const code = fs.readFileSync(checkFile, "utf8");

      expect(code).not.toContain(dir);

      result = await runCli(["precompile", "--check", file]);

      expect(result).toEqual({ exitCode: 0, log: [], error: [] });

      // Nothing to write when it is up to date
      result = await runCli(["precompile", file]);

      expect(result).toEqual({ exitCode: 0, log: [], error: [] });

      writeJson("src/options.json", { type: "string" });

      result = await runCli(["precompile", "--check", file]);

      expect(result.exitCode).toBe(1);
      expect(result.error[0]).toMatch(/options\.check\.js" is out of date/);
      expect(fs.readFileSync(checkFile, "utf8")).toBe(code);
    });

    it("should report a schema it cannot precompile and go on", async () => {
      const broken = path.join(dir, "broken.json");

      fs.writeFileSync(broken, "{");

      const file = writeJson("options.json", { type: "string" });
      const result = await runCli(["precompile", broken, file]);

      expect(result.exitCode).toBe(1);
      expect(result.error[0]).toMatch(/^Cannot precompile ".+broken\.json": /);
      expect(fs.existsSync(path.join(dir, "options.check.js"))).toBe(true);
    });
  });
});
